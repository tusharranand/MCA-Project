from __future__ import annotations

from typing import Any, Dict, List, Optional

import pandas as pd


class PredictionService:
    """Deterministic risk scorer for the academic churn prototype."""

    def __init__(
        self,
        model_version: str = "v1.0.0",
        threshold: float = 0.4,
        high_risk_threshold: float = 0.7,
        model: Optional[Any] = None,
        feature_columns: Optional[List[str]] = None,
    ) -> None:
        self.model_version = model_version
        self.threshold = float(threshold)
        self.high_risk_threshold = float(high_risk_threshold)
        self.model = model
        self.feature_columns = feature_columns or []

    def classify_risk(self, probability: float) -> str:
        probability = float(probability)
        if probability >= self.high_risk_threshold:
            return "High"
        if probability >= self.threshold:
            return "Medium"
        return "Low"

    def _safe_float(self, value: object) -> float:
        if value is None:
            return 0.0
        try:
            return float(value)
        except (TypeError, ValueError):
            return 0.0

    def score(self, features: Dict[str, object]) -> Dict[str, object]:
        if self.model is not None:
            model_input = pd.DataFrame([features]).reindex(columns=self.feature_columns)
            probabilities = self.model.predict_proba(model_input)[0]
            classes = list(self.model.named_steps["classifier"].classes_)
            probability = float(probabilities[classes.index("Yes")])
            return {
                "risk_probability": round(probability, 4),
                "risk_band": self.classify_risk(probability),
                "model_version": self.model_version,
                "explanation": [
                    "Risk estimate generated by the saved churn model pipeline.",
                    "This estimate is advisory and should be reviewed by a human analyst.",
                ],
            }

        age = self._safe_float(features.get("Age"))
        tenure = self._safe_float(features.get("Tenure_Months"))
        monthly_spend = self._safe_float(features.get("Monthly_Spend_INR"))
        tickets = self._safe_float(features.get("Support_Tickets_90D"))
        resolution_hours = self._safe_float(features.get("Avg_Resolution_Hours"))
        satisfaction = self._safe_float(features.get("Satisfaction_Score"))
        days_since_activity = self._safe_float(features.get("Days_Since_Last_Activity"))

        probability = 0.12
        if age > 55:
            probability += 0.08
        if tenure < 12:
            probability += 0.12
        if monthly_spend > 1500:
            probability += 0.08
        if tickets > 2:
            probability += 0.18
        if resolution_hours > 18:
            probability += 0.12
        if satisfaction < 3:
            probability += 0.18
        if days_since_activity > 30:
            probability += 0.10

        probability = min(0.96, max(0.02, probability))
        risk_band = self.classify_risk(probability)

        explanation = [
            "Recent engagement, service, and spend signals are being compared against the historical churn profile.",
            "The score is a prototype risk estimate and should be reviewed by a human analyst before any intervention.",
        ]

        return {
            "risk_probability": round(probability, 4),
            "risk_band": risk_band,
            "model_version": self.model_version,
            "explanation": explanation,
        }
